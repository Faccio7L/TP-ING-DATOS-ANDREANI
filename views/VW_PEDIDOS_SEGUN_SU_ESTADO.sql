CREATE VIEW VW_PEDIDOS_SEGUN_SU_ESTADO
    --MUESTRA LA CANTIDAD DE PEDIDOS SEGUN SU ESTADO Y MUESTRA SUS DETALLES.
    AS
    WITH CANTIDAD_POR_ESTADO AS(
        SELECT COUNT(P.IdPedido) AS CANTIDAD, P.EstadoPedido
        FROM PEDIDO P
        GROUP BY P.EstadoPedido
    )
    SELECT CPE.CANTIDAD, CPE.EstadoPedido, DP.CantidadSolicitada, DP.IdPedido,DP.IdProducto
    FROM CANTIDAD_POR_ESTADO CPE
    INNER JOIN PEDIDO P ON P.EstadoPedido = CPE.EstadoPedido
    INNER JOIN DETALLEPEDIDO DP ON DP.IdPedido = P.IdPedido

