USE andreani
GO

CREATE TABLE CLIENTE(
    IDCLIENTE INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRECLIENTE VARCHAR(50) NOT NULL
)
GO
CREATE TABLE DESTINO(
    IDDESTINO INT IDENTITY(1,1) PRIMARY KEY,
    NOMBREDESTINO VARCHAR(100) NOT NULL,
    TIPODESTINO VARCHAR(30) CHECK (TIPODESTINO IN ('FARMACIA', 'CLINICA', 'DROGERIA', 'HOSPITAL')) NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    CIUDAD VARCHAR(50) NOT NULL,
    PROVINCIA VARCHAR(50) NOT NULL
)
GO
CREATE TABLE PRODUCTO(
    IDPRODUCTO INT IDENTITY(1,1) PRIMARY KEY,
    NOMBREPRODUCTO VARCHAR(100) NOT NULL,
    CATEGORIAPRODUCTO VARCHAR(50) NOT NULL,
    TEMPERATURAMIN DECIMAL(4,1) NOT NULL DEFAULT -30,
    TEMPERATURAMAX DECIMAL(4,1) NOT NULL DEFAULT 40,
    CONSTRAINT VALIDACION_TEMPERATURA CHECK (
        TEMPERATURAMIN < TEMPERATURAMAX 
        AND TEMPERATURAMIN >= -30 
        AND TEMPERATURAMAX <= 40
    )
)
GO
CREATE TABLE LOTE(
    IDLOTE INT IDENTITY(1,1) PRIMARY KEY,
    IDPRODUCTO INT FOREIGN KEY REFERENCES PRODUCTO(IDPRODUCTO),
    FECHAVENCIMIENTO DATE NOT NULL,
    ESTADO VARCHAR(20) DEFAULT 'DISPONIBLE' CHECK (ESTADO IN ('DISPONIBLE','BLOQUEADO','VENCIDO')),
    STOCKLOTE INT NOT NULL CHECK (STOCKLOTE >= 0)
)   
GO