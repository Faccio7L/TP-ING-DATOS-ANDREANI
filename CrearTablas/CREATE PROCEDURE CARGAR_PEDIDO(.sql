CREATE PROCEDURE CARGAR_PEDIDO(
    @IDCLIENTE INT,
    @IDDESTINO INT,
    @FECHAENTREGASOLICITADA DATE ,
    @TEMPERATURAPEDIDO DECIMAL(5,3)
)
    AS
    BEGIN
    BEGIN TRY
    BEGIN TRANSACTION

    DECLARE @EXISTE_CLIENTE INT
    DECLARE @EXISTE_DESTINO INT

    SELECT @EXISTE_CLIENTE = C.IDCLIENTE
    FROM CLIENTE C
    WHERE C.IDCLIENTE = @IDCLIENTE

    IF @EXISTE_CLIENTE IS NULL
    BEGIN
        PRINT('CLIENTE NO REGISTRADO EN SISTEMA.')
        RETURN
    END
    
    SELECT @EXISTE_DESTINO = D.IDDESTINO
    FROM DESTINO D
    WHERE D.IDDESTINO = @IDDESTINO
    
    IF @EXISTE_DESTINO IS NULL
    BEGIN 
        PRINT('EL DESTINO NO ESTA CARGADO EN EL SISTEMA.')
        RETURN
    END
    
    IF @FECHAENTREGASOLICITADA <= GETDATE()
    BEGIN
        PRINT('FECHA INVALIDA.')
        RETURN
    END

    INSERT PEDIDO(IdCliente,IdDestino,FechaEntregaSolicitada,TemperaturaPedido)
    VALUES(@IDCLIENTE,@IDDESTINO,@FECHAENTREGASOLICITADA,@TEMPERATURAPEDIDO)
    COMMIT TRANSACTION

    END TRY
    BEGIN CATCH 
    ROLLBACK
    PRINT('HA OCURRIDO UN ERROR')
    END CATCH
    END
GO

CREATE PROCEDURE CREAR_DETALE_PEDIDO(
    @IDPEDIDO INT,
    @IDPRODUCTO INT,
    @CANTIDAD INT
)
    AS
    BEGIN
    BEGIN TRY
    BEGIN TRANSACTION

    DECLARE @ESTADOPEDIDO VARCHAR
    DECLARE @STOCK INT

    SELECT @IDPEDIDO = P.IdPedido
    FROM PEDIDO P
    WHERE P.IdPedido = @IDPEDIDO
    IF @IDPEDIDO IS NULL 
    BEGIN
    PRINT('EL PEDIDO NO EXISTE')
    RETURN
    END

    SELECT @STOCK = L.STOCKLOTE
    FROM LOTE L
    WHERE L.IDPRODUCTO = @IDPRODUCTO AND L.FECHAVENCIMIENTO > GETDATE() --ACA PODRIAMOS HACER UN PROCEDIMIENTO QUE SI QUEDAN 7 DIAS O MENOS QUE SE ELIMINE EL LOTE, ESTO PODRIA FUNCIONAR COMO VALIDACION EXTRA.
    --ACA TRABAJA GEMINI--
    IF @STOCK < @CANTIDAD
    BEGIN
    PRINT('NO HAY STOCK SUFICIENTE(sin considerar posibles productos vencidos).')
    BREAK
    END

    SELECT @IDPRODUCTO = P.IDPRODUCTO
    FROM PRODUCTO P
    WHERE P.IDPRODUCTO = @IDPRODUCTO
    IF @IDPRODUCTO IS NULL
    BEGIN
    PRINT('NO EXISTE EL PRODUCTO.')
    BREAK

    INSERT DETALLEPEDIDO(IDPRODUCTO,CantidadSolicitada)
    VALUES DETALLEPEDIDO(@IDPRODUCTO,@CANTIDAD)
    COMMIT TRANSACTION
    END TRY
    BEGIN CATCH
    PRINT('HA OCURRIDO UN ERROR')
    ROLLBACK
    END CATCH
    END

    


    

    
    
    