--TRAZABILIDAD DE UN LOTE (RF08).
--¿CUÁL ES LA RUTA EXACTA DE UN LOTE ESPECÍFICO, INCLUYENDO QUÉ MEDICAMENTO ES, CUÁNTO SE PREPARÓ,
--EN QUÉ CAJA FUE, EN QUÉ DESPACHO VIAJÓ Y QUIÉN LO RECIBIÓ?
--
--DEVUELVE UNA FILA POR CADA PREPARACIÓN (Y CAJA) EN LA QUE SE USÓ EL LOTE, CON TODO EL RECORRIDO:
--LOTE -> PRODUCTO -> PREPARACION -> DETALLECAJA -> CAJA -> DESPACHO -> VEHICULO -> ENTREGA -> DESTINO.
--SE USAN LEFT JOIN DESDE LA CAJA EN ADELANTE PARA QUE TAMBIÉN APAREZCAN LOS LOTES QUE TODAVÍA NO
--TERMINARON EL RECORRIDO (EJ: PREPARADO PERO SIN CAJA, O EN CAJA PERO SIN DESPACHO). EN ESE CASO
--LAS COLUMNAS QUE FALTAN QUEDAN EN NULL Y LA COLUMNA ETAPA_ACTUAL INDICA DÓNDE ESTÁ EL LOTE.
--"QUIÉN LO RECIBIÓ" ES EL DESTINO DEL PEDIDO (FARMACIA, CLÍNICA, HOSPITAL O DROGUERÍA), Y SOLO SE
--MUESTRA EN RECIBIDO_POR CUANDO LA ENTREGA QUEDÓ COMO 'Entregada'.
--
--USO: SELECT * FROM FN_TRAZABILIDAD_LOTE(1)
CREATE FUNCTION FN_TRAZABILIDAD_LOTE(
    @IDLOTE INT
)
RETURNS TABLE
AS
RETURN
(
    SELECT
        L.IDLOTE,
        PR.IDPRODUCTO,
        PR.NOMBREPRODUCTO AS MEDICAMENTO,
        PR.CATEGORIAPRODUCTO,
        L.FECHAVENCIMIENTO,
        PRE.IdPreparacion,
        PRE.IdPedido,
        CL.NOMBRECLIENTE AS CLIENTE,
        PRE.FechaPreparacion,
        PRE.CantidadPreparada,
        PRE.CumpleFEFO,
        C.IdCaja,
        C.CodigoBarra,
        DC.CantidadEmpacada,
        C.EstadoCaja,
        D.IdDespacho,
        D.FechaSalida,
        D.EstadoDespacho,
        V.Patente AS PATENTE_VEHICULO,
        DE.NOMBREDESTINO AS DESTINO,
        DE.TIPODESTINO,
        DE.DIRECCION,
        DE.CIUDAD,
        DE.PROVINCIA,
        E.FechaEntregaReal,
        E.EstadoEntrega,
        E.LlegoFrio,
        CASE WHEN E.EstadoEntrega = 'Entregada' THEN DE.NOMBREDESTINO END AS RECIBIDO_POR,
        CASE
            WHEN E.EstadoEntrega = 'Entregada' THEN 'ENTREGADO'
            WHEN E.EstadoEntrega = 'Rechazada' THEN 'RECHAZADO EN DESTINO'
            WHEN D.EstadoDespacho = 'En ruta' THEN 'EN VIAJE'
            WHEN D.IdDespacho IS NOT NULL THEN 'ASIGNADO A DESPACHO'
            WHEN C.IdCaja IS NOT NULL THEN 'EN CAJA'
            ELSE 'PREPARADO SIN CAJA'
        END AS ETAPA_ACTUAL
    FROM LOTE L
    INNER JOIN PRODUCTO PR ON PR.IDPRODUCTO = L.IDPRODUCTO
    INNER JOIN PREPARACION PRE ON PRE.IdLote = L.IDLOTE
    INNER JOIN PEDIDO P ON P.IdPedido = PRE.IdPedido
    INNER JOIN CLIENTE CL ON CL.IDCLIENTE = P.IdCliente
    INNER JOIN DESTINO DE ON DE.IDDESTINO = P.IdDestino
    LEFT JOIN DETALLECAJA DC ON DC.IdPreparacion = PRE.IdPreparacion
    LEFT JOIN CAJA C ON C.IdCaja = DC.IdCaja
    LEFT JOIN DESPACHO D ON D.IdDespacho = C.IdDespacho
    LEFT JOIN VEHICULO V ON V.IdVehiculo = D.IdVehiculo
    LEFT JOIN ENTREGA E ON E.IdPedido = PRE.IdPedido AND E.IdDespacho = C.IdDespacho
    WHERE L.IDLOTE = @IDLOTE
)
GO
